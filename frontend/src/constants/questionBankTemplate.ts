export const QUESTION_BANK_TEMPLATE: QuestionBankTemplateRow[] = RAW_TEMPLATE
  .split('\n')
  .map((line) => line.trim())
  .filter(Boolean)
  .map((line) => {
    const [sNo, qType, questionLabel, btl, co, marks, part, college] = line.split(/\s+/);
    return {
      s_no: Number(sNo),
      question_type: (qType === 'O' ? 'O' : 'D') as 'D' | 'O',
      question_label: String(questionLabel || ''),
      btl: Number(btl),
      course_outcome: String(co || ''),
      marks: Number(marks),
      part: String(part || ''),
      college: String(college || ''),
    };
  })
  .sort((a, b) => a.s_no - b.s_no);
