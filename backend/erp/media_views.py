"""
Protected media serving.

In production nginx must NOT serve ``/media/`` directly. Instead every media
request is routed through this view which authorizes it and then:

- behind nginx: issues ``X-Accel-Redirect: /protected-media/<relpath>`` so
  nginx performs the actual file I/O (fast, no Python streaming);
- in development / without nginx: streams the file directly.

Authorization policy (deny-by-default):

1. Path matches one of ``PUBLIC_MEDIA_PREFIXES`` → anonymous access allowed
   (profile images, announcement covers/themes, event posters).
2. Otherwise the request must be authenticated (Django session, JWT header,
   or JWT httpOnly cookie).
3. As an escape hatch for <img>/<a> tags that cannot carry auth headers or
   cookies, a short-lived signed URL can be used: ``?sig=...&expires=...``
   generated by :func:`signed_media_url`.

Traversal-safe: the resolved path is forced under ``MEDIA_ROOT``.
"""
from __future__ import annotations

import mimetypes
import os
import posixpath
import time
from pathlib import Path

from django.conf import settings
from django.core.signing import Signer, BadSignature
from django.http import (
    FileResponse,
    HttpResponse,
    HttpResponseForbidden,
    HttpResponseNotFound,
)
from django.views import View

from erp.authentication import authenticate_request


def _media_root() -> Path:
    root = getattr(settings, 'MEDIA_ROOT', None)
    return Path(root).resolve() if root else None


def _public_prefixes() -> list[str]:
    raw = getattr(settings, 'PUBLIC_MEDIA_PREFIXES', None)
    if raw is None:
        raw = [
            'profile_images/',
            'announcements/covers/',
            'announcements/themes/',
            'event_posters/',
        ]
    return [str(p).strip('/') + '/' for p in raw if str(p).strip()]


def _is_public(rel_path: str) -> bool:
    rel = rel_path.lstrip('/')
    return any(rel.startswith(prefix) for prefix in _public_prefixes())


def _safe_resolve(rel_path: str) -> Path | None:
    """Resolve ``rel_path`` under MEDIA_ROOT, rejecting traversal."""
    root = _media_root()
    if root is None:
        return None
    rel = posixpath.normpath(rel_path).lstrip('/')
    if rel in ('', '.', '..'):
        return None
    if rel.startswith('../') or '/../' in rel or rel == '..':
        return None
    candidate = (root / rel).resolve()
    try:
        candidate.relative_to(root)
    except ValueError:
        return None
    return candidate


def _use_x_accel() -> bool:
    return bool(getattr(settings, 'USE_X_ACCEL_REDIRECT', not settings.DEBUG))


def signed_media_url(rel_path: str, ttl_seconds: int = 600) -> str:
    """Return a short-lived signed URL for a media file.

    Use this in serializers/views when a protected file must be rendered in an
    ``<img src=...>`` or downloaded via ``<a href=...>``.
    """
    signer = Signer(salt='media-protected')
    expires = int(time.time()) + int(ttl_seconds)
    signed = signer.sign(f"{expires}:{rel_path.lstrip('/')}")
    return f"{settings.MEDIA_URL}{rel_path.lstrip('/')}?sig={signed}&expires={expires}"


class ProtectedMediaView(View):
    http_method_names = ['get', 'head', 'options']

    def get(self, request, path):
        rel_path = path or ''
        resolved = _safe_resolve(rel_path)
        if resolved is None or not resolved.exists() or not resolved.is_file():
            return HttpResponseNotFound('Not found.')

        # 1) Public prefixes — no auth required.
        authorized = _is_public(rel_path)

        # 2) Authenticated request (session / JWT header / JWT cookie).
        if not authorized:
            user = authenticate_request(request)
            authorized = user is not None and user.is_authenticated

        # 3) Signed URL fallback.
        if not authorized:
            authorized = self._check_signature(request, rel_path)

        if not authorized:
            return HttpResponseForbidden(
                'Authentication required to access this file.'
            )

        content_type = mimetypes.guess_type(str(resolved))[0] or 'application/octet-stream'

        if _use_x_accel():
            response = HttpResponse()
            response['Content-Type'] = content_type
            response['X-Accel-Redirect'] = '/protected-media/' + posixpath.normpath(rel_path).lstrip('/')
            return response

        response = FileResponse(resolved.open('rb'), content_type=content_type)
        response['Content-Length'] = resolved.stat().st_size
        response['Content-Disposition'] = 'inline; filename="%s"' % os.path.basename(str(resolved))
        return response

    def _check_signature(self, request, rel_path: str) -> bool:
        sig = request.GET.get('sig', '')
        try:
            expires = int(request.GET.get('expires', '0'))
        except (TypeError, ValueError):
            return False
        if expires < time.time():
            return False

        signer = Signer(salt='media-protected')
        try:
            unsigned = signer.unsign(sig)
        except BadSignature:
            return False
        # Signature must be scoped to this exact path and expiry.
        return unsigned == f"{expires}:{rel_path.lstrip('/')}"
